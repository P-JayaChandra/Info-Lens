import pytest
from app.rate_limiting.rate_limiting_service_08 import (
    Rate_limitingConfig8,
    Rate_limitingState8,
    Rate_limitingProcessor8,
)

def test_rate_limiting_unit_config_8():
    cfg = Rate_limitingConfig8()
    assert cfg.enabled is True
    assert cfg.max_capacity == 1000
    assert cfg.batch_size == 64

def test_rate_limiting_unit_state_8():
    state = Rate_limitingState8(name="init_state", value=10.0)
    assert state.name == "init_state"
    assert state.value == 10.0
    state.record_metric(20.0)
    assert state.compute_average() == 15.0

def test_rate_limiting_unit_proc_8_op_1():
    proc = Rate_limitingProcessor8()
    sample_data = [{"weight": 1.2, "score": 0.8}, {"weight": 0.5, "score": 0.3}]
    result = proc.execute_operation_1(sample_data, scale_factor=1.5)
    assert result["batch_size"] == 2
    assert "mean" in result
    assert len(proc.audit_trail) == 1

